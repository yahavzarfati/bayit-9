const prefix = 'bayit-9-dashboard';
const provider = { getIcon: async name => ({ path: Object.hasOwn(paths, name) ? paths[name] : '' }) };

export function bundledHomeIcon(icon, view) {
  if (!icon.startsWith('mdi:')) return icon;
  const name = icon.slice(4);
  if (!Object.hasOwn(paths, name)) return icon;

  const registry = view.customIcons ??= {};
  if (!Object.hasOwn(registry, prefix)) registry[prefix] = provider;
  return registry[prefix] === provider ? prefix + ':' + name : icon;
}
